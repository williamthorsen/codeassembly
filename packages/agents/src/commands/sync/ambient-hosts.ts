import { appendAmbientRegion, classifyAmbientRegion, injectAmbientRegion } from '../../lib/ambient-region.ts';
import { writeIfChanged } from '../../lib/fs-helpers.ts';
import { checkGitIgnored } from '../../lib/git-ignore.ts';
