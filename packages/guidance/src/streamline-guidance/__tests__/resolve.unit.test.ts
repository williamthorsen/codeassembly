import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { runResolve } from '../cli.ts';
import { RECORD_PATH } from '../record.ts';
import { makeFakeGit } from '../test-utils/make-fake-git.ts';
import type { HelperFailure, ResolveSuccess } from '../types.ts';

const TARGET = 'lib/skills/demo/SKILL.md';

/** A repository's committed files: one content root, whose skill includes a partial that includes and links onward. */
const REPOSITORY_FILES: Readonly<Record<string, string>> = {
  '.agents/preferences.yaml': 'artifacts:\n  base_dir: artifacts\n',
  'AGENTS.md':
    '# Guide\n\n<!-- codeassembly-ambient:start -->\nGenerated.\n<!-- codeassembly-ambient:end -->\n\nAuthored.\n',
  'artifacts/note.md': 'A saved artifact.\n',
  'lib/codeassembly-content.yaml': 'format: 2\n',
  'lib/_partials/inner.md': 'Inner text.\n',
  'lib/_partials/shared.md': 'Shared text. See [ref](../_data/ref.md).\n\n<!-- include: ./inner.md / -->\n',
  'lib/skills/_data/deep.md': 'Deep.\n',
  'lib/skills/_data/other.md': 'Other.\n',
  'lib/skills/_data/ref.md': 'Reference. See [deep](./deep.md).\n',
  'lib/skills/_data/types.json': '{}\n',
  'lib/guidance/_harnesses/claude/CLAUDE.md': 'Guidance.\n',
  [TARGET]: [
    '---',
    'name: demo',
    '---',
    '',
    '<!-- include: ../../_partials/shared.md / -->',
    '',
    'Read `{harness_home_dir}/skills/_sources/codeassembly/_data/other.md`.',
    '',
    'See [types]({harness_home_dir}/skills/_data/types.json).',
    '',
  ].join('\n'),
  'notes.txt': 'Not guidance.\n',
};

/**
 * Files outside the repository: deployed copies in a harness home, and an authored file that is not in git.
 * `{repository}` stands for the repository's absolute path.
 */
const HOME_FILES: Readonly<Record<string, string>> = {
  '.claude/CLAUDE.md':
    '<!-- GENERATED FILE - Do not edit this file. -->\n<!-- Source: guidance/_harnesses/claude/CLAUDE.md in source "codeassembly" ({repository}/lib) -->\n\nGuidance.\n',
  '.rovo/AGENTS.md':
    '<!-- GENERATED FILE - Do not edit this file. -->\n<!-- Source: guidance/_harnesses/claude/CLAUDE.md in source "codeassembly" (/elsewhere/checkout/lib) -->\n\nGuidance.\n',
  '.claude/skills/demo/SKILL.md': '---\nname: demo\n---\n<!-- codeassembly-skill:demo -->\n\nDeployed.\n',
  '.claude/skills/orphan/SKILL.md': '---\nname: orphan\n---\n<!-- codeassembly-skill:orphan -->\n\nDeployed.\n',
  'loose.md': 'Loose.\n',
};

describe(runResolve, () => {
  /** Files that git reports as modified, staged, or untracked. */
  let changed: string[];
  /** Files that git lists as tracked, or as untracked and not ignored. */
  let files: string[];
  let home: string;
  let repository: string;
  let scratch: string;

  beforeEach(async () => {
    scratch = await realpath(await mkdtemp(path.join(tmpdir(), 'streamline-resolve-')));
    repository = path.join(scratch, 'repository');
    home = path.join(scratch, 'home');
    await writeFiles(repository, REPOSITORY_FILES);
    await writeFiles(
      home,
      Object.fromEntries(
        Object.entries(HOME_FILES).map(([file, content]) => [
          file,
          content.replaceAll('{repository}', () => repository),
        ]),
      ),
    );
    files = Object.keys(REPOSITORY_FILES);
    changed = [];
  });

  afterEach(async () => {
    await rm(scratch, { recursive: true, force: true });
  });

  it("reports a target's includes, recursively, and the Markdown files to which it and its includes link", async () => {
    const result = expectSuccess(await resolve(TARGET));

    expect(result.targets.map((target) => target.file)).toStrictEqual([TARGET]);
    expect(result.transitive.map(({ file, via }) => ({ file, via }))).toStrictEqual([
      { file: 'lib/_partials/inner.md', via: [{ from: 'lib/_partials/shared.md', kind: 'include' }] },
      { file: 'lib/_partials/shared.md', via: [{ from: TARGET, kind: 'include' }] },
      { file: 'lib/skills/_data/other.md', via: [{ from: TARGET, kind: 'link' }] },
      // The partial's link resolves against the skill that renders it, not against the partial's own directory.
      { file: 'lib/skills/_data/ref.md', via: [{ from: 'lib/_partials/shared.md', kind: 'link' }] },
    ]);
  });

  it.each([
    { copy: '.claude/skills/demo/SKILL.md', source: TARGET, marker: 'an ownership marker' },
    { copy: '.claude/CLAUDE.md', source: 'lib/guidance/_harnesses/claude/CLAUDE.md', marker: 'a Source line' },
    {
      copy: '.rovo/AGENTS.md',
      source: 'lib/guidance/_harnesses/claude/CLAUDE.md',
      marker: 'a Source line naming another checkout',
    },
  ])('if a named path is a deployed copy containing $marker, resolves it to its source', async ({ copy, source }) => {
    const copyPath = path.join(home, copy);

    const result = expectSuccess(await resolve(copyPath));

    expect(result.targets).toMatchObject([{ file: source, redirectedFrom: copyPath }]);
  });

  it.each([
    { named: () => path.join(home, 'loose.md'), reason: 'outside-repository' },
    { named: () => path.join(home, '.claude/skills/orphan/SKILL.md'), reason: 'source-not-in-repository' },
    { named: () => 'artifacts/note.md', reason: 'saved-artifact' },
    { named: () => 'notes.txt', reason: 'not-markdown' },
    { named: () => 'missing.md', reason: 'not-found' },
  ])('if a named path cannot be a target, rejects it as $reason', async ({ named, reason }) => {
    const namedPath = named();

    const result = expectSuccess(await resolve(namedPath));

    expect(result.targets).toStrictEqual([]);
    expect(result.rejected).toStrictEqual([{ path: namedPath, reason }]);
  });

  it('expands a named directory to the Markdown files beneath it', async () => {
    const result = expectSuccess(await resolve('lib/_partials'));

    expect(result.targets.map((target) => target.file).toSorted()).toStrictEqual([
      'lib/_partials/inner.md',
      'lib/_partials/shared.md',
    ]);
  });

  it('rejects a file beneath a named directory whose include does not resolve, and resolves the others', async () => {
    await changeFiles({
      'lib/notes/README.md': [
        '<!-- include: ../_partials/inner.md / -->',
        '',
        'An example directive:',
        '',
        '```',
        '<!-- include: _partials/example.md / -->',
        '```',
        '',
      ].join('\n'),
      'lib/notes/guide.md': 'A guide.\n',
    });

    const result = expectSuccess(await resolve('lib/notes'));

    expect(result.targets.map((target) => target.file)).toStrictEqual(['lib/notes/guide.md']);
    expect(result.transitive).toStrictEqual([]);
    expect(result.rejected).toStrictEqual([{ path: 'lib/notes/README.md', reason: 'unresolved-include' }]);
  });

  it("reports the line range of a target's generated region", async () => {
    const result = expectSuccess(await resolve('AGENTS.md'));

    expect(result.targets).toMatchObject([{ file: 'AGENTS.md', generatedRegions: [{ start: 3, end: 5 }] }]);
  });

  it('marks only a file with uncommitted changes as dirty', async () => {
    await changeFiles({ 'lib/_partials/shared.md': 'Shared text.\n' });

    const result = expectSuccess(await resolve('lib/_partials/shared.md', 'lib/_partials/inner.md', 'AGENTS.md'));

    expect(Object.fromEntries(result.targets.map((target) => [target.file, target.dirty]))).toStrictEqual({
      'AGENTS.md': false,
      'lib/_partials/inner.md': false,
      'lib/_partials/shared.md': true,
    });
  });

  it('reports only the declined cuts whose phrase their file still contains', async () => {
    await changeFiles({
      [RECORD_PATH]: [
        'declined:',
        '  - file: lib/_partials/shared.md',
        '    phrase: Shared   text.',
        '    class: conservative',
        '    declined-at: 2026-09-01',
        '  - file: lib/_partials/shared.md',
        '    phrase: Removed text.',
        '    class: moderate',
        '    declined-at: 2026-09-01',
        '',
      ].join('\n'),
    });

    const result = expectSuccess(await resolve(TARGET));

    expect(result.declined).toStrictEqual([
      { file: 'lib/_partials/shared.md', phrase: 'Shared   text.', class: 'conservative' },
    ]);
  });

  it("reports a reviewed file's last review, and omits it for a file that the record does not review", async () => {
    await changeFiles({
      [RECORD_PATH]: [
        'reviewed:',
        `  - file: ${TARGET}`,
        '    reviewed-at: 2026-09-01',
        '    deployed-bytes: 512',
        '',
      ].join('\n'),
    });

    const result = expectSuccess(await resolve(TARGET));

    expect(result.targets[0]?.lastReview).toStrictEqual({ reviewedAt: '2026-09-01', deployedBytes: 512 });
    expect(result.transitive.every((file) => file.lastReview === undefined)).toBe(true);
  });

  describe('deployed bytes', () => {
    it("reports a document's deployed bytes as the size of its body once its includes are expanded", async () => {
      const source = ['xy', '', '<!-- include: ../../_partials/tiny.md / -->', ''].join('\n');
      await changeFiles({ 'lib/_partials/tiny.md': 'ab\n', 'lib/skills/sized/SKILL.md': source });

      const result = expectSuccess(await resolve('lib/skills/sized/SKILL.md'));

      expect(result.targets).toMatchObject([{ bytes: source.length, deployedBytes: 'xy\n\nab\n'.length }]);
    });

    it("reports a partial's deployed bytes as its own bytes times the documents that include it", async () => {
      await changeFiles({
        'lib/skills/second/SKILL.md': '<!-- include: ../../_partials/shared.md / -->\n',
      });

      const result = expectSuccess(await resolve('lib/_partials/inner.md'));

      // Both skills include the partial, the second of them through `shared.md`.
      expect(result.targets).toMatchObject([
        { bytes: 'Inner text.\n'.length, deployedBytes: 'Inner text.\n'.length * 2 },
      ]);
    });

    it.each([
      {
        shape: 'an unclosed open directive',
        body: ['Text.', '<!-- include: ../../_partials/inner.md -->', ''].join('\n'),
      },
      {
        shape: 'an include cycle',
        body: ['Text.', '<!-- include: ../../_partials/loop.md / -->', ''].join('\n'),
      },
    ])('omits the field for a file containing $shape, and keeps it a target', async ({ body }) => {
      await changeFiles({
        'lib/_partials/loop.md': '<!-- include: ./loop-back.md / -->\n',
        'lib/_partials/loop-back.md': '<!-- include: ./loop.md / -->\n',
        'lib/skills/broken/SKILL.md': body,
      });

      const result = expectSuccess(await resolve('lib/skills/broken/SKILL.md'));

      expect(result.rejected).toStrictEqual([]);
      expect(result.targets).toHaveLength(1);
      expect(result.targets[0]).not.toHaveProperty('deployedBytes');
    });

    it('omits the field for a file that lies outside every content root', async () => {
      const result = expectSuccess(await resolve('AGENTS.md'));

      expect(result.targets).toHaveLength(1);
      expect(result.targets[0]).not.toHaveProperty('deployedBytes');
    });
  });

  describe('failures', () => {
    it('if the working directory is not in a repository, fails as not-a-repository', async () => {
      const result = await runResolve({ argv: ['loose.md'], cwd: home, home }, makeFakeGit({}));

      expect(result).toMatchObject({ ok: false, error: 'not-a-repository' });
    });

    it('if the record is malformed, fails as invalid-record', async () => {
      await changeFiles({ [RECORD_PATH]: 'declined:\n  - file: x.md\n' });

      expect(await resolve(TARGET)).toMatchObject({ ok: false, error: 'invalid-record' });
    });
  });

  /** Writes files into the repository as uncommitted changes, which git lists and reports as changed. */
  async function changeFiles(changes: Readonly<Record<string, string>>): Promise<void> {
    await writeFiles(repository, changes);
    for (const file of Object.keys(changes)) {
      if (!files.includes(file)) files.push(file);
      changed.push(file);
    }
  }

  /** Runs `resolve` from the repository root against the fixture home. */
  async function resolve(...paths: string[]): Promise<HelperFailure | ResolveSuccess> {
    return runResolve({ argv: paths, cwd: repository, home }, makeFakeGit({ topLevel: repository, files, changed }));
  }
});

// region | Helpers

/** Narrows a result to success, failing the test with the failure's message otherwise. */
function expectSuccess(result: HelperFailure | ResolveSuccess): ResolveSuccess {
  if (!result.ok) {
    throw new Error(`expected success, got ${result.error}: ${result.message}`);
  }
  return result;
}

/** Writes each file beneath a root, creating its directories. */
async function writeFiles(root: string, files: Readonly<Record<string, string>>): Promise<void> {
  for (const [file, content] of Object.entries(files)) {
    await mkdir(path.dirname(path.join(root, file)), { recursive: true });
    await writeFile(path.join(root, file), content, 'utf8');
  }
}

// endregion | Helpers
