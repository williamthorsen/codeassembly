import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/** Location of the committed module that exports the conversion's instructions. */
export const CONVERSION_INSTRUCTIONS_PATH = path.resolve(import.meta.dirname, 'conversion-instructions.ts');

/** The documents whose text, in this order, makes up the conversion's instructions. */
const SOURCE_PATHS = ['agent-instructions.md', 'extraction-rules.md'].map((file) =>
  path.resolve(import.meta.dirname, '../../docs', file),
);

/** Reads the conversion's instructions from `docs/`: the conversion procedure followed by the extraction rules. */
export function readConversionInstructions(): string {
  return SOURCE_PATHS.map((file) => readFileSync(file, 'utf8')).join('\n');
}

/** Renders the text of the module that exports the instructions as a string, so that a browser bundle can import it. */
export function renderConversionInstructionsModule(): string {
  return [
    '// Generated by write-conversion-instructions.ts from docs/agent-instructions.md and docs/extraction-rules.md. Do',
    '// not edit.',
    '',
    "/** The conversion's instructions: the conversion procedure followed by the extraction rules. */",
    `export const CONVERSION_INSTRUCTIONS = ${JSON.stringify(readConversionInstructions())};`,
    '',
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(CONVERSION_INSTRUCTIONS_PATH, renderConversionInstructionsModule());
}
